package com.protocol.app.openport2

/**
 * SSM2 ECM diagnostic trouble codes (read-only).
 *
 * Each code is a single bit in the ECU's diagnostic status memory. The ECU
 * keeps two copies: a "current" (temporary) byte that reflects faults present
 * right now, and a "stored" (memorized) byte for faults logged in memory.
 * Reading codes is therefore the same A8 read-address operation the live-data
 * path uses — point it at the status bytes and test each code's bit.
 *
 * Table columns: code | description | currentAddr(hex) | storedAddr(hex) | bit.
 * Sourced from the per-ECU diagnostic bit map for this engine family.
 */
data class DtcDef(
    val code: String,
    val description: String,
    val tmpAddr: Int,
    val memAddr: Int,
    val bit: Int
)

object DtcCatalog {

    val ALL: List<DtcDef> = TABLE.lineSequence()
        .filter { it.isNotBlank() }
        .map { line ->
            val p = line.split('|')
            DtcDef(p[0], p[1], p[2].toInt(16), p[3].toInt(16), p[4].toInt())
        }
        .toList()

    /** Distinct "current" status-byte addresses to read (sorted). */
    val currentAddrInts: List<Int> = ALL.map { it.tmpAddr }.distinct().sorted()

    /** Distinct "stored" status-byte addresses to read (sorted). */
    val storedAddrInts: List<Int> = ALL.map { it.memAddr }.distinct().sorted()

    /** 24-bit SSM2 address int -> 3-byte [Ssm2Address]. */
    fun toAddress(a: Int): Ssm2Address = Ssm2Address(
        ((a shr 16) and 0xFF).toByte(),
        ((a shr 8) and 0xFF).toByte(),
        (a and 0xFF).toByte()
    )

    /** Codes whose "current" bit is set in [bytesByAddr] (addr int -> byte). */
    fun decodeCurrent(bytesByAddr: Map<Int, Int>): List<DtcDef> =
        ALL.filter { (((bytesByAddr[it.tmpAddr] ?: 0) shr it.bit) and 1) == 1 }

    /** Codes whose "stored" bit is set in [bytesByAddr] (addr int -> byte). */
    fun decodeStored(bytesByAddr: Map<Int, Int>): List<DtcDef> =
        ALL.filter { (((bytesByAddr[it.memAddr] ?: 0) shr it.bit) and 1) == 1 }
}

